CREATE TABLE AUTHOR (
  ID  BIGINT IDENTITY(1,1) PRIMARY KEY,
    TIME_PERIOD VARCHAR(255),
    SPOTIFY_DATA_TIME_INTERVAL_ID BIGINT,
    LITHIUM_UUID VARCHAR(255),
    AUTHOR_NOTES NVARCHAR(max),
    CONVERSATION_IDS VARCHAR(255),
    QUEUE_ID VARCHAR(255),
    USERNAMES VARCHAR(500),
    TWITTER_HANDLES VARCHAR(500),
    FACEBOOK_DISPLAY_NAMES VARCHAR(500),
    GOOGLE_MESSENGER_DISPLAY_NAMES VARCHAR(500),
    INSTAGRAM_HANDLES VARCHAR(500),
    YOUTUBE_HANDLES VARCHAR(500),
    LINKEDIN_HANDLES VARCHAR(500),
    SMS_HANDLES VARCHAR(500),
    WECHAT_NAMES VARCHAR(500),
    RECORD_STATUS VARCHAR(50),
    PLAYVOX_ACKNOWLEDGEMENT_ID VARCHAR(255),
    CREATED_DATE DATETIME NOT NULL,
    CREATED_BY VARCHAR(20) NOT NULL,
    UPDATED_DATE DATETIME,
    UPDATED_BY VARCHAR(20)
      INDEX idx_SPOTIFY_DATA_TIME_INTERVAL_ID (SPOTIFY_DATA_TIME_INTERVAL_ID)
);